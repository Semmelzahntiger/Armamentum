package com.semmelzahntiger.arms.common.blocks.base;

import com.google.common.base.Suppliers;
import com.semmelzahntiger.arms.common.blockentities.base.GunBaseBlockEntity;
import com.semmelzahntiger.arms.common.blockentities.base.GunBaseBlockExtensionBlockEntity;
import com.semmelzahntiger.arms.common.entities.GunEntity;
import com.semmelzahntiger.arms.helper.MiscUtil;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.core.Vec3i;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.EntityBlock;
import net.minecraft.world.level.block.RenderShape;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.BlockEntityTicker;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.block.state.properties.DirectionProperty;
import org.apache.commons.lang3.function.TriFunction;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Supplier;

public abstract class GunBaseBlock<G extends Entity & GunEntity> extends Block implements EntityBlock {

    public static final DirectionProperty FACING = BlockStateProperties.HORIZONTAL_FACING;

    protected final Supplier<Map<Direction, List<OffsetBlockStatePair>>> offsets = Suppliers.memoize(this::buildOffsets);

    public GunBaseBlock(Properties properties) {
        super(properties);
        registerDefaultState(stateDefinition.any()
                .setValue(FACING, Direction.NORTH));
    }


    public abstract @NotNull TriFunction<BlockPos, BlockState,List<Vec3i>, BlockEntity> getBlockEntityFactory();

    public int getPlatformLength() {
        return 1;
    }
    public int getPlatformWidth() {
        return 1;
    }
    public int getPlatformHeight() {
        return 1;
    }

    /**
     * Generates the offsets for the extension blocks
     */
    protected List<OffsetBlockStatePair> generateOffsets() {
        List<OffsetBlockStatePair> offsets = new ArrayList<>();
        // +X for East
        int width = getPlatformWidth();
        // -Z for North
        int length = getPlatformLength();
        int height = getPlatformHeight();

        for (int x = -(width - 1) / 2; x <= width / 2; x++) {
            for (int z = -(length - 1) / 2; z <= length / 2; z++) {
                for (int y = 0; y < height; y++) {
                    if(x == 0 && y == 0&&z == 0) continue;
                    Vec3i offset = new Vec3i(x,y,-z);
                    offsets.add(new OffsetBlockStatePair(offset, getBlockStateForOffset(offset)));
                }
            }
        }
        return offsets;
    }

    /**
     * Takes the offsets generated by {@link generateOffsets()} and adjusts them for each cardinal direction
     */
    protected Map<Direction, List<OffsetBlockStatePair>> buildOffsets() {
        Map<Direction, List<OffsetBlockStatePair>> map = new HashMap<>();
        List<OffsetBlockStatePair> northOffsets = generateOffsets();
        for (Direction facing : Direction.Plane.HORIZONTAL) {
            List<OffsetBlockStatePair> rotated = northOffsets.stream()
                    .map(offsetPair ->
                            new OffsetBlockStatePair(MiscUtil.rotateOffsetToFacing(offsetPair.offset(), facing), offsetPair.state()))
                    .toList();
            map.put(facing, rotated);
        }
        return map;
    }

    protected abstract BlockState getBlockStateForOffset(Vec3i offset);


    /** The structure cell offsets for the orientation this state was placed with. */
    public List<OffsetBlockStatePair> getActiveOffsetPairs(BlockState state) {
        return offsets.get().get(state.getValue(FACING));
    }
    public List<Vec3i> getActiveOffsets(BlockState state) {
        return getActiveOffsetPairs(state).stream().map(OffsetBlockStatePair::offset).toList();
    }

    protected boolean areOffsetsFree(Level level, BlockPos pos, BlockState state) {
        for (OffsetBlockStatePair pair : getActiveOffsetPairs(state)) {
            if (!level.getBlockState(pos.offset(pair.offset())).canBeReplaced()) {
                return false;
            }
        }
        return true;
    }

    /**
     * @param direction Cardinal Direction
     * @return offsets based on the cardinal direction
     */
    public List<OffsetBlockStatePair> getOffsetsFromDirection(Direction direction) {
        return offsets.get().get(direction);
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING);
    }

    @Override
    public @Nullable BlockState getStateForPlacement(BlockPlaceContext context) {
        BlockState state = defaultBlockState()
                .setValue(FACING, context.getHorizontalDirection());
        return areOffsetsFree(context.getLevel(), context.getClickedPos(), state) ? state : null;
    }

    @Override
    public final @Nullable BlockEntity newBlockEntity(@NotNull BlockPos blockPos, @NotNull BlockState blockState) {
        return getBlockEntityFactory().apply(blockPos, blockState, getOffsetsFromDirection(blockState.getValue(FACING)).stream().map(OffsetBlockStatePair::offset).toList());
    }
    @SuppressWarnings("unchecked")
    public GunBaseBlockEntity<G> getGunBaseBlockEntity(Level level, BlockPos blockPos) {
        return (GunBaseBlockEntity<G>) level.getBlockEntity(blockPos);
    }


    @Override
    protected void onPlace(BlockState state, Level level, BlockPos pos, BlockState oldState, boolean movedByPiston) {
        super.onPlace(state, level, pos, oldState, movedByPiston);
        placeStructure(level, pos, state);
    }
    protected void placeStructure(Level level, BlockPos pos, BlockState state) {
        for (OffsetBlockStatePair pair : getActiveOffsetPairs(state)) {
            BlockPos offsetPos = pos.offset(pair.offset());
            BlockState extensionState = pair.state();
            extensionState = extensionState.trySetValue(GunBaseBlockExtension.FACING, state.getValue(FACING));
            level.setBlockAndUpdate(offsetPos, extensionState);
        }
    }

    @Override
    protected void onRemove(BlockState state, Level level, BlockPos pos, BlockState newState, boolean movedByPiston) {
        GunBaseBlockEntity<G> gunBaseBlockEntity = getGunBaseBlockEntity(level, pos);
        for (OffsetBlockStatePair pair : getActiveOffsetPairs(state)) {
            BlockPos extensionPos = pos.offset(pair.offset());
            if(
                    level.getBlockState(extensionPos).getBlock() instanceof GunBaseBlockExtension<?> extension &&
                    extension.getBlockEntity(level, extensionPos) instanceof GunBaseBlockExtensionBlockEntity<?> be &&
                    pos.equals(be.getLinkedBlockPos())
            ) {
                level.removeBlock(extensionPos, false);
            }
        }
        if(gunBaseBlockEntity != null) {
            gunBaseBlockEntity.onBreak();
        }
        super.onRemove(state, level, pos, newState, movedByPiston);
    }
    @SuppressWarnings("unchecked")
    private static <E extends BlockEntity, A extends BlockEntity> @Nullable BlockEntityTicker<A> createTickerHelper(
            BlockEntityType<A> type, BlockEntityType<E> checkedType, BlockEntityTicker<? super E> ticker
    ) {
        return checkedType == type ? (BlockEntityTicker<A>) ticker : null;
    }

    @Override
    public @Nullable <T extends BlockEntity> BlockEntityTicker<T> getTicker(@NotNull Level level, @NotNull BlockState state, @NotNull BlockEntityType<T> blockEntityType) {
        return createTickerHelper(blockEntityType, getCheckedBlockEntityType(), GunBaseBlockEntity::tick);
    }
    public abstract @NotNull BlockEntityType<? extends GunBaseBlockEntity<?>> getCheckedBlockEntityType();

    @Override
    protected @NotNull RenderShape getRenderShape(BlockState state) {
        return RenderShape.INVISIBLE;
    }

}
